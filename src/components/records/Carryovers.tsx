import { RecordShell } from "./RecordShell";
import { NumberCell } from "./NumberCell";
import type { RecordCtx } from "@/lib/records/ctx";
import { line } from "@/lib/checks/helpers";
import { toCents, type Cents } from "@/lib/money";
import { tieOut, type TieOut } from "@/lib/records/tieout";

export function Carryovers({ model, versionId, meta }: RecordCtx) {
  const into = (model.raw.prior_years as Record<string, unknown>).carryovers_into_2025 as Record<string, unknown>;
  const ver = model.versionById.get(versionId);
  const out = (ver as unknown as { carryovers_out?: { federal?: Record<string, number>; california?: Record<string, unknown> } })?.carryovers_out;
  const outFed = out?.federal ?? {};
  const d = (x: unknown): Cents | null => toCents(x);

  const rows: Array<{ label: string; into: Cents | null; out: Cents | null; usedNote: string }> = [
    { label: "Capital loss carryover — short-term", into: d(into.capital_loss_short), out: d(outFed.capital_loss_short), usedNote: "Used on Sch D line 6" },
    { label: "Capital loss carryover — long-term", into: d(into.capital_loss_long), out: d(outFed.capital_loss_long), usedNote: "Used on Sch D line 14" },
    { label: "Passive loss — 1450 Fremont", into: d(into.passive_1450_fremont), out: d(outFed.passive_1450_fremont), usedNote: "Released (F8582)" },
    { label: "Passive loss — 1200 Barton Hills", into: d(into.passive_1200_barton_hills), out: d(outFed.passive_1200_barton_hills), usedNote: "Released (F8582)" },
    { label: "AMT / minimum-tax credit", into: d(into.amt_credit), out: d(outFed.minimum_tax_credit_from_2025_amt), usedNote: "Generated by 2025 AMT" },
    { label: "SEP — nondeductible for 2025", into: 0n, out: d(outFed.sep_contribution_not_deductible_for_2025), usedNote: "Compliance (CPA to determine)" },
    { label: "Ridgeline capital account (end)", into: null, out: d(outFed.ridgeline_capital_account_end), usedNote: "Outside basis never computed" },
  ];

  const caDep = (out?.california as { depreciation_basis_differences?: Record<string, number> })?.depreciation_basis_differences ?? {};

  const tieOuts: TieOut[] = [
    tieOut("ST loss carryover used", "SchD.6", d(into.capital_loss_short) ?? 0n, absCents(line(model, versionId, "SchD.6")?.value)),
    tieOut("LT loss carryover used", "SchD.14", d(into.capital_loss_long) ?? 0n, absCents(line(model, versionId, "SchD.14")?.value)),
  ];

  return (
    <RecordShell title="15. Carryovers" slug="carryovers" meta={meta} tieOuts={tieOuts}>
      <p className="text-xs text-slate-500">
        Into 2025 (from the 2024 return D06 + prior preparer D07) → used in 2025 → out to 2026.
      </p>
      <div className="card scroll-box">
        <table className="w-full text-sm">
          <thead className="bg-slate-50 text-left text-xs uppercase text-slate-500">
            <tr>
              <th className="px-3 py-2">Carryover</th>
              <th className="px-3 py-2 text-right">Into 2025</th>
              <th className="px-3 py-2 text-right">Out to 2026</th>
              <th className="px-3 py-2">Used / note</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.label} className="border-t border-slate-100">
                <td className="px-3 py-2">{r.label}</td>
                <td className="px-3 py-2 text-right"><NumberCell cents={r.into} /></td>
                <td className="px-3 py-2 text-right"><NumberCell cents={r.out} /></td>
                <td className="px-3 py-2 text-xs text-slate-500">{r.usedNote}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      <div className="card p-3">
        <div className="mb-1 text-xs font-semibold uppercase tracking-wide text-slate-500">
          California depreciation basis differences (out to 2026)
        </div>
        <ul className="grid grid-cols-2 gap-1 text-sm md:grid-cols-4">
          {Object.entries(caDep).map(([asset, amt]) => (
            <li key={asset} className="flex justify-between gap-2">
              <span className="mono">{asset}</span>
              <span className="mono">{Number(amt).toLocaleString()}</span>
            </li>
          ))}
        </ul>
      </div>
    </RecordShell>
  );
}

function absCents(x: unknown): Cents | null {
  const c = toCents(x);
  if (c === null) return null;
  return c < 0n ? -c : c;
}
